import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const read = (path) => readFile(new URL(path, root), "utf8");

const [
  html,
  authCss,
  appCss,
  designCss,
  historicalSales,
  dataSource,
  support,
  firebaseConfigSource,
  firebaseSource,
  authSource,
] = await Promise.all([
  read("index.html"),
  read("src/auth.css"),
  read("src/app-overrides.css"),
  read("_ds/modernist-e875d6f4-63c8-49e5-bac6-bc1922b4958c/styles.css"),
  read("src/historical-sales.js"),
  read("src/data-source.js"),
  read("support.js"),
  read("src/firebase-config.js"),
  read("src/firebase.js"),
  read("src/auth.js"),
]);

const stripImports = (source) => source.replace(
  /import\s*\{[\s\S]*?\}\s*from\s*"[^"]+";\s*/g,
  "",
);
const safeInlineScript = (source) => source.replace(/<\/script/gi, "<\\/script");
const safeInlineStyle = (source) => source.replace(/<\/style/gi, "<\\/style");

const firebaseConfig = firebaseConfigSource.replace(
  "export const firebaseConfig",
  "const firebaseConfig",
);
const firebaseBootstrap = stripImports(firebaseSource).replace(
  /export\s*\{\s*app,\s*auth\s*\};\s*/,
  "",
);
const authBootstrap = stripImports(authSource);
const firebaseModule = `
import { getApp, getApps, initializeApp } from "https://www.gstatic.com/firebasejs/12.19.0/firebase-app.js";
import {
  browserLocalPersistence,
  getAuth,
  getIdTokenResult,
  onAuthStateChanged,
  reload,
  sendEmailVerification,
  sendPasswordResetEmail,
  setPersistence,
  signInWithEmailAndPassword,
  signOut,
} from "https://www.gstatic.com/firebasejs/12.19.0/firebase-auth.js";

${firebaseConfig}
${firebaseBootstrap}
${authBootstrap}
`;

const externalHead = [
  '<link rel="stylesheet" href="./src/auth.css">',
  '<script type="module" src="./src/firebase.js"></script>',
  '<script type="module" src="./src/auth.js"></script>',
  '<script src="./src/historical-sales.js"></script>',
  '<script src="./src/data-source.js"></script>',
  '<script src="./support.js"></script>',
].join("\n");
const inlineHead = [
  '<style id="labkit-bundled-styles">',
  safeInlineStyle([designCss, authCss, appCss].join("\n")),
  "</style>",
  "<script>window.__LABKIT_APPS_SCRIPT__ = true;</script>",
  "<script>",
  safeInlineScript(historicalSales),
  "</script>",
  "<script>",
  safeInlineScript(dataSource),
  "</script>",
  '<script type="module">',
  safeInlineScript(firebaseModule),
  "</script>",
  "<script>",
  safeInlineScript(support),
  "</script>",
].join("\n");

let output = html.replace(externalHead, inlineHead);
if (output === html) {
  throw new Error("Could not find the expected browser asset block in index.html");
}

output = output
  .replace('  <link rel="stylesheet" href="_ds/modernist-e875d6f4-63c8-49e5-bac6-bc1922b4958c/styles.css">\n', "")
  .replace('  <link rel="stylesheet" href="src/app-overrides.css">\n', "")
  .replace('  <script src="_ds/modernist-e875d6f4-63c8-49e5-bac6-bc1922b4958c/_ds_bundle.js"></script>\n', "")
  .replace(
    "<!DOCTYPE html>",
    "<!DOCTYPE html>\n<!-- Generated by scripts/build-apps-script.mjs. Copy this entire file into Apps Script Index.html. -->",
  );

if (/src="\.\//.test(output) || /href="(?:\.\/)?src\//.test(output)) {
  throw new Error("Generated Apps Script HTML still contains a local asset reference");
}
if (!output.includes("window.__LABKIT_APPS_SCRIPT__ = true")) {
  throw new Error("Generated Apps Script HTML is missing its runtime marker");
}

await writeFile(new URL("apps-script/Index.html", root), output, "utf8");
console.log("Built Apps Script frontend in apps-script/Index.html");
